import 'package:nyumba_mtaani/entities/property_entity.dart';

class PropertyModel extends PropertyEntity {
  const PropertyModel({
    required super.id,
    required super.title,
    required super.slug,
    required super.propertyType,
    required super.listingPurpose,
    required super.price,
    super.pricePeriod,
    super.currency,
    super.bedrooms,
    super.bathrooms,
    super.sizeSqm,
    super.description,
    required super.status,
    required super.locationText,
    super.latitude,
    super.longitude,
    super.coverImageUrl,
    super.videoUrls,
    super.imageIds,
    super.features,
    required super.createdAt,
    super.ownerId,
    super.agentId,
    super.isFeatured,
    super.isVerified,
  });

  factory PropertyModel.fromJson(Map<String, dynamic> json) {
    return PropertyModel(
      id: json['id'] as String,
      title: json['title'] as String,
      slug: json['slug'] as String,
      propertyType: json['property_type'] as String,
      listingPurpose: json['listing_purpose'] as String,
      price: (json['price'] as num).toDouble(),
      pricePeriod: json['price_period'] as String? ?? 'monthly',
      currency: json['currency'] as String? ?? 'KES',
      bedrooms: json['bedrooms'] as int?,
      bathrooms: json['bathrooms'] as int?,
      sizeSqm: json['size_sqm'] != null ? (json['size_sqm'] as num).toDouble() : null,
      description: json['description'] as String?,
      status: json['status'] as String,
      locationText: json['location_text'] as String,
      latitude: (json['latitude'] as num?)?.toDouble(),
      longitude: (json['longitude'] as num?)?.toDouble(),
      coverImageUrl: json['cover_image_url'] as String?,
      videoUrls: (json['video_urls'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [],
      imageIds: (json['image_ids'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [],
      features: (json['features'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [],
      createdAt: DateTime.parse(json['created_at'] as String),
      ownerId: json['owner_id'] as String?,
      agentId: json['agent_id'] as String?,
      isFeatured: json['is_featured'] as bool? ?? false,
      isVerified: json['is_verified'] as bool? ?? false,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'title': title,
      'slug': slug,
      'property_type': propertyType,
      'listing_purpose': listingPurpose,
      'price': price,
      'price_period': pricePeriod,
      'currency': currency,
      'bedrooms': bedrooms,
      'bathrooms': bathrooms,
      'size_sqm': sizeSqm,
      'description': description,
      'status': status,
      'location_text': locationText,
      'latitude': latitude,
      'longitude': longitude,
      'cover_image_url': coverImageUrl,
      'video_urls': videoUrls,
      'image_ids': imageIds,
      'features': features,
      'created_at': createdAt.toIso8601String(),
      'owner_id': ownerId,
      'agent_id': agentId,
      'is_featured': isFeatured,
      'is_verified': isVerified,
    };
  }
}
